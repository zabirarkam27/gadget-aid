import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { createServer } from "vite";
import react from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";
const require = createRequire(import.meta.url);
const {createApp}=require("../../gadget-aid-server/app.js");
const {createFixture,verifyIdToken,fixedTime}=require("../../gadget-aid-server/tests/fixtures.cjs");
const fixture=createFixture({seedBooking:true,seedInProgress:true});
const qaStartedAt=Date.now();
const api=createApp({getCollections:async()=>fixture.db,verifyIdToken,clock:()=>new Date(fixedTime.getTime()+Date.now()-qaStartedAt),origins:["http://127.0.0.1:5176","http://localhost:5176"]});
const apiServer=api.listen(5055,"127.0.0.1");
const clientRoot=fileURLToPath(new URL("../",import.meta.url));
const server=await createServer({configFile:false,root:resolve(clientRoot,"tests/qa"),envDir:clientRoot,publicDir:resolve(clientRoot,"public"),plugins:[react(),tailwindcss()],define:{"import.meta.env.VITE_API_URL":JSON.stringify("http://127.0.0.1:5055")},resolve:{alias:[{find:/^.*\/utils\/authFetch(?:\.js)?$/,replacement:resolve(clientRoot,"tests/qa/transport.js")}]},server:{host:"127.0.0.1",port:5176,strictPort:true,fs:{allow:[resolve(clientRoot,"..")]}},clearScreen:false});
await server.listen();
console.log("Isolated QA ready: http://127.0.0.1:5176/booked-services (memory database, fixed demo identities; no production connection)");
const close=async()=>{await server.close();apiServer.closeAllConnections();apiServer.close(()=>process.exit(0));};
process.on("SIGINT",close);process.on("SIGTERM",close);
